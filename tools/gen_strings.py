#!/usr/bin/env python3
"""Generate the typed string accessors from the neutral (English) .resx files.

    python3 tools/gen_strings.py           regenerate every *.g.cs
    python3 tools/gen_strings.py --check   exit 1 if any *.g.cs is out of date

MSBuild's own strongly-typed resource generation (StronglyTypedLanguage) does not
run in WPF's temporary markup-compile project, so GanttIt.Revit could not see the
class. The accessors are therefore generated here and committed, like a
Visual Studio *.Designer.cs; the Core test ResourceTests.GeneratedAccessorsMatchResx
fails when one is stale.

Each <data> entry becomes a property (no placeholders) or a method with one
`object? argN` parameter per {N} placeholder, so a call with the wrong number of
arguments does not compile. Lookups go through GanttIt.Core.Localization.UiLanguage,
which passes the UI culture to the ResourceManager explicitly (the thread cultures
are never changed).
"""

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent

# (neutral resx, namespace, class name, manifest resource base name)
TARGETS = [
    ("src/GanttIt.Core/Resources/CoreStrings.resx", "GanttIt.Core.Resources", "CoreStrings",
     "GanttIt.Core.Resources.CoreStrings"),
    ("src/GanttIt.Revit/Resources/Strings.resx", "GanttIt.Revit.Resources", "Strings",
     "GanttIt.Revit.Resources.Strings"),
]

PLACEHOLDER = re.compile(r"(?<!\{)\{(\d+)(?:[,:][^}]*)?\}")


def entries(resx: Path):
    for data in ET.parse(resx).getroot().iter("data"):
        value = data.find("value")
        yield data.get("name"), (value.text or "") if value is not None else ""


def arity(text: str) -> int:
    indexes = [int(m.group(1)) for m in PLACEHOLDER.finditer(text.replace("{{", "").replace("}}", ""))]
    return max(indexes) + 1 if indexes else 0


def generate(resx_rel: str, namespace: str, cls: str, base_name: str) -> str:
    out = [
        "// <auto-generated>",
        f"//   Generated by tools/gen_strings.py from {Path(resx_rel).name}. Do not edit:",
        "//   change the .resx files and run `python3 tools/gen_strings.py`.",
        "// </auto-generated>",
        "#nullable enable",
        "",
        "using System.Resources;",
        "using GanttIt.Core.Localization;",
        "",
        f"namespace {namespace};",
        "",
        f"/// <summary>UI strings from {Path(resx_rel).name}, looked up in <see cref=\"UiLanguage.Culture\"/>.</summary>",
        f"internal static class {cls}",
        "{",
        f"    internal static readonly ResourceManager ResourceManager = new(\"{base_name}\", typeof({cls}).Assembly);",
        "",
        "    /// <summary>The string <paramref name=\"key\"/> in the UI language (the key itself when missing).</summary>",
        "    internal static string Get(string key) => UiLanguage.GetString(ResourceManager, key);",
        "",
        "    private static string Format(string key, params object?[] args) => UiLanguage.Format(ResourceManager, key, args);",
    ]
    for name, text in entries(ROOT / resx_rel):
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name or ""):
            raise SystemExit(f"{resx_rel}: '{name}' is not a valid identifier")
        doc = escape(text).replace("\n", " ").replace("\r", " ")
        out.append("")
        out.append(f"    /// <summary>{doc}</summary>")
        n = arity(text)
        if n == 0:
            out.append(f"    internal static string {name} => Get(\"{name}\");")
        else:
            params = ", ".join(f"object? arg{i}" for i in range(n))
            args = ", ".join(f"arg{i}" for i in range(n))
            out.append(f"    internal static string {name}({params}) => Format(\"{name}\", {args});")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for resx_rel, namespace, cls, base_name in TARGETS:
        target = (ROOT / resx_rel).with_name(f"{cls}.g.cs")
        text = generate(resx_rel, namespace, cls, base_name)
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == text:
            continue
        if check:
            stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {target.relative_to(ROOT)}")
    if stale:
        print("out of date (run python3 tools/gen_strings.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
